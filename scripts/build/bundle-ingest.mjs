// Produces web/dist/ingest-server.mjs: the file the `ingest` service in
// docker-compose.yml actually runs (see docker-compose.yml's comment on
// that service for why a build step is needed at all).
//
// Unlike the agent bundle (scripts/build/bundle-agent.mjs), this file runs
// INSIDE the same Docker image as the Next.js `web` service -- the full
// monorepo, with `npm ci` already run and workspace symlinks intact. So
// this bundle does NOT need to be fully standalone; real npm dependencies
// (`ws`, the generated `@prisma/client`) are left external and resolved
// from that image's node_modules at runtime, exactly as `next start` does
// for the `web` service.
//
// What DOES need bundling: every relative import under web/src/server and
// web/src/lib (ingest-server.ts, auth-agent.ts, ingest.ts, agent-socket.ts,
// db.ts, ingest-server-config.ts, staleness.ts, ...) is written the
// NodeNext way -- `from './auth-agent.js'` pointing at a sibling
// `auth-agent.ts` -- which only a bundler or `tsc` resolves; plain Node
// cannot (see the compose file's comment on the `ingest` command). The
// workspace package `@bevora-ops/shared` has the same problem one level
// up: its `package.json` points `main`/`types` straight at
// `shared/src/index.ts`, so `require('@bevora-ops/shared')` in a plain
// Node process would try to load TypeScript source directly. Leaving it
// external would just move today's failure from "ingest-server.ts" to
// "@bevora-ops/shared" instead of fixing it, so it is bundled IN rather
// than externalised, along with its own dependency `zod`.
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(here, '../..')

await build({
  entryPoints: [path.join(repoRoot, 'web/src/server/ingest-server.ts')],
  outfile: path.join(repoRoot, 'web/dist/ingest-server.mjs'),
  bundle: true,
  platform: 'node',
  target: 'node22',
  // ESM, unlike the agent bundle: ingest-server.ts gates its own
  // self-start (`if (import.meta.url === \`file://${process.argv[1]}\`)`)
  // on `import.meta.url`, which esbuild leaves EMPTY when the output
  // format is "cjs" (confirmed by building this bundle: esbuild warns
  // `"import.meta" is not available with the "cjs" output format` and the
  // guard silently never fires, so the listener never starts). Node's
  // native ESM support gives `import.meta.url` its real value, so the
  // guard behaves exactly as it does today under `tsx`/vitest. The
  // `.mjs` extension forces ESM interpretation regardless of any ancestor
  // `package.json`'s `"type"` field (web/package.json sets none).
  format: 'esm',
  sourcemap: false,
  minify: false,
  logLevel: 'info',
  // Real npm dependencies of the image this runs in -- resolved from that
  // image's node_modules at runtime, never inlined. `@prisma/client`
  // specifically must stay external: its generated code locates the
  // native query-engine binary relative to its own on-disk location, which
  // breaks if esbuild inlines it into a different file.
  external: ['ws', '@prisma/client', '.prisma/client'],
  banner: {
    js: '// Generated by `npm run build:ingest` from web/src/server/ingest-server.ts -- do not edit by hand.',
  },
})
