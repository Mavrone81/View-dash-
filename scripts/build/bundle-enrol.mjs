// Produces web/dist/enrol-cli.mjs -- the operator command `deploy/README.md`
// tells a human to run to mint an agent token. Same rationale as
// scripts/build/bundle-ingest.mjs: web/src/server/enrol-cli.ts is a
// standalone script (never part of Next's own bundling) that imports
// sibling `.ts` files via `.js`-suffixed relative specifiers, which plain
// Node cannot resolve without a build step. It runs inside the same image
// as `web`/`ingest`, so real npm dependencies stay external and resolve
// from that image's node_modules, exactly as the ingest bundle does.
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(here, '../..')

await build({
  entryPoints: [path.join(repoRoot, 'web/src/server/enrol-cli.ts')],
  outfile: path.join(repoRoot, 'web/dist/enrol-cli.mjs'),
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  sourcemap: false,
  minify: false,
  logLevel: 'info',
  external: ['@prisma/client', '.prisma/client'],
  banner: {
    js: '// Generated by `npm run build:enrol` from web/src/server/enrol-cli.ts -- do not edit by hand.',
  },
})
