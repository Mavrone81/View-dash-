// Produces the ONE file that ships to a monitored host: agent/dist/agent-bundle.cjs.
//
// That host has no monorepo, no workspace symlinks, and no TypeScript --
// `@bevora-ops/shared` (imported by agent/src/*.ts as a workspace package)
// resolves only inside this repo's npm workspace. This bundle inlines it,
// and every other agent dependency, into a single CommonJS file so the
// deployment story is "copy one file, run it with plain `node`" -- no
// `npm install`, no node_modules, no package.json, on the target machine.
//
// Format: CJS, not ESM. Two of the agent's real dependencies (dockerode's
// docker-modem, and transitively ssh2) are written as CommonJS with
// conditional/optional `require(...)` calls (see the cpu-features note
// below); bundling them into a CJS output keeps esbuild's interop simple
// and avoids ESM's stricter static-import/top-level-await rules for code
// this project does not own. Plain `node agent-bundle.cjs` runs a `.cjs`
// file as CommonJS regardless of any nearby package.json, so there is no
// ambiguity on the target host.
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(here, '../..')

await build({
  entryPoints: [path.join(repoRoot, 'agent/src/main.ts')],
  outfile: path.join(repoRoot, 'agent/dist/agent-bundle.cjs'),
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'cjs',
  sourcemap: false,
  minify: false,
  logLevel: 'info',
  // TRUE NATIVE DEPENDENCIES, externalised on purpose: dockerode ->
  // docker-modem unconditionally requires an SSH-based transport
  // (docker-modem/lib/ssh.js) that this agent never uses (main.ts always
  // connects via the default local Docker socket, `new Docker()` with no
  // options). That transport's `ssh2` dependency:
  //   - does `try { require('cpu-features') } catch {}` (a separate npm
  //     package, ssh2/lib/protocol/constants.js) to probe for a compiled
  //     addon that speeds up algorithm negotiation, and
  //   - does `try { require('./crypto/build/Release/sshcrypto.node') }
  //     catch {}` (a file inside ssh2 itself, ssh2/lib/protocol/crypto.js)
  //     for accelerated cipher implementations,
  // both of which are compiled .node binaries esbuild cannot embed in a JS
  // bundle. `*.node` externalises any such binary wherever it is required;
  // `cpu-features` externalises that one by package name since it is
  // required as a bare specifier, not a path. On the target host (no
  // node_modules) both throw MODULE_NOT_FOUND, which ssh2's own try/catch
  // swallows exactly as it does today when these optional natives are
  // simply not installed. Nothing in this agent's actual code path (Docker
  // discovery over the local socket, deploy-log/git reads, the outbound
  // WebSocket transport) ever reaches this code.
  external: ['cpu-features', '*.node'],
  banner: { js: '// Generated by `npm run build:agent` from agent/src/main.ts -- do not edit by hand.' },
})
